def ask(prompt: str, options: list[str], default: int = 1) -> int:
    """Numbered menu. Returns a 1-based index."""
    print(f"\n{BOLD}{prompt}{ENDC}")
    for index, option in enumerate(options, 1):
        marker = f" {DIM}(default){ENDC}" if index == default else ""
        print(f"  {index}. {option}{marker}")

    while True:
        raw = input(f"\n{GREEN}Choice [{default}]:{ENDC} ").strip()
        if not raw:
            return default
        if raw.isdigit() and 1 <= int(raw) <= len(options):
            return int(raw)
        print(f"  Enter 1-{len(options)}")


def ask_number(prompt: str, default: float) -> float:
    raw = input(f"\n{GREEN}{prompt} [{default}]:{ENDC} ").strip()
    if not raw:
        return default
    try:
        return float(raw)
    except ValueError:
        print(f"  {YELLOW}Not a number, using {default}{ENDC}")
        return default


def run_wizard(skill_dir: Path) -> int:
    print(f"\n{CYAN}{'═' * 68}{ENDC}")
    print(f"{BOLD}  ALGOTRADER — BOT GENERATOR{ENDC}")
    print(f"{CYAN}{'═' * 68}{ENDC}")

    style_choice = ask(
        "Trading style?",
        ["Intraday — square off daily, minute bars",
         "Swing — hold 3-10 days, 15-minute bars",
         "Positional — hold weeks, daily bars"],
        default=1,
    )
    style = ["intraday", "swing", "positional"][style_choice - 1]

    universe_choice = ask(
        "Universe?",
        ["Nifty 50 — largecap, tightest spreads",
         "Nifty 100",
         "Nifty Midcap 150 — more volatile, breakouts follow through",
         "Nifty Smallcap 250 — widest spreads, check liquidity carefully"],
        default=1,
    )
    universe_key = ["nifty50", "nifty100", "midcap150", "smallcap250"][universe_choice - 1]

    strategy_choice = ask(
        "Strategy?",
        ["Fortress — six-factor confirmation (highest win rate)",
         "Momentum — breakout continuation (suits midcaps)",
         "Mean reversion — VWAP pullback (suits largecaps)"],
        default=1,
    )
    strategy = ["fortress", "momentum", "mean_reversion"][strategy_choice - 1]

    capital = ask_number("Starting capital in lakhs", 10.0) * 100_000

    risk_choice = ask(
        "Risk per trade?",
        ["Conservative — 0.5%", "Balanced — 1.0%", "Aggressive — 2.0%"],
        default=2,
    )
    risk_pct = [0.5, 1.0, 2.0][risk_choice - 1]

    config = json.loads((skill_dir / "config" / "default.json").read_text())
    config.update({
        "strategy": strategy,
        "capital": capital,
        "risk_pct": risk_pct,
        "universe_file": f"universe/{universe_key}.json",
        "interval": {"intraday": "minute", "swing": "15minute", "positional": "day"}[style],
        "product": "MIS" if style == "intraday" else "CNC",
    })

    if style == "intraday":
        config.update({"max_hold_minutes": 45, "sl_atr_mult": 1.2, "risk_reward": 1.5,
                       "close_on_shutdown": True})
    elif style == "swing":
        config.update({"max_hold_minutes": 0, "sl_atr_mult": 2.0, "risk_reward": 2.0,
                       "squareoff_time": None, "close_on_shutdown": False,
                       "trail_pct": 3.0, "max_positions": 8})
    else:
        config.update({"max_hold_minutes": 0, "sl_atr_mult": 2.5, "risk_reward": 3.0,
                       "squareoff_time": None, "close_on_shutdown": False,
                       "trail_pct": 8.0, "max_positions": 10, "skip_lunch": False,
                       "use_regime_sizing": True})

    name = input(f"\n{GREEN}Bot name [trading_bot]:{ENDC} ").strip() or "trading_bot"
    folder = Path(f"{name}_{datetime.now():%Y%m%d_%H%M%S}")

    print(f"\n{BOLD}Summary{ENDC}")
    print(f"  Style      {style} ({config['interval']} bars, {config['product']})")
    print(f"  Strategy   {strategy}")
    print(f"  Universe   {universe_key}")
    print(f"  Capital    Rs {capital:,.0f}")
    print(f"  Risk       {risk_pct}% per trade → max loss Rs {capital * risk_pct / 100:,.0f}")
    print(f"  Folder     {folder}")

    if input(f"\n{GREEN}Generate? [Y/n]:{ENDC} ").strip().lower() in ("n", "no"):
        print("  Cancelled.")
        return 1

    folder.mkdir(parents=True, exist_ok=True)
    (folder / "config.json").write_text(json.dumps(config, indent=2))

    # Copy the engine so the bot is self-contained and version-frozen.
    shutil.copytree(skill_dir / "engine", folder / "engine", dirs_exist_ok=True)
    shutil.copytree(skill_dir / "config", folder / "config", dirs_exist_ok=True)

    substitutions = {
        "name": name,
        "date": datetime.now().strftime("%Y-%m-%d"),
        "strategy": strategy,
        "universe": universe_key,
        "universe_file": config["universe_file"],
        "capital": capital,
        "risk_pct": risk_pct,
        "max_positions": config["max_positions"],
        "heat": config["max_portfolio_heat_pct"],
        "daily_loss": config["daily_loss_limit_pct"],
        "streak": config["max_consecutive_losses"],
        "squareoff": config.get("squareoff_time") or "n/a",
    }

    (folder / "main.py").write_text(MAIN_TEMPLATE.format(**substitutions))
    (folder / "main.py").chmod(0o755)
    (folder / "README.md").write_text(README_TEMPLATE.format(**substitutions))
    (folder / ".env.template").write_text(ENV_TEMPLATE)
    (folder / ".gitignore").write_text(
        ".env\n.kite_session.json\n.cache/\nlogs/\nstate/\n__pycache__/\n*.pyc\n"
    )

    print(f"\n  fetching {universe_key} constituents from NSE...")
    try:
        from engine.universe import fetch_index_constituents, save_universe

        data = fetch_index_constituents(universe_key)
        save_universe(data, folder / config["universe_file"])
        print(f"  {GREEN}✓{ENDC} {data['count']} symbols")
    except Exception as exc:  # noqa: BLE001
        print(f"  {YELLOW}!{ENDC} universe fetch failed ({exc})")
        print(f"    run: ./run.sh universe --indices {universe_key} --out {folder}/universe")

    print(f"\n{GREEN}Generated {folder}{ENDC}\n")
    print(f"{BOLD}Next{ENDC}")
    print(f"  1. cd {folder}")
    print("  2. cp .env.template .env   and fill in your Kite API key/secret")
    print("  3. python -m engine.broker login   (then ...token <request_token>)")
    print("  4. python main.py --backtest --start 2026-01-01")
    print("  5. python main.py --mode paper")
    print(f"\n{DIM}  Read NUANCES.md before step 5, and before ever using --mode live.{ENDC}")
    return 0
