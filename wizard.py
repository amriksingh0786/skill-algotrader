from engine.runner import TradingRunner, PreflightError


def load_config() -> dict:
    return json.loads((BOT_DIR / "config.json").read_text())


def main() -> int:
    parser = argparse.ArgumentParser(description="{name}")
    parser.add_argument("--mode", choices=["paper", "live"], default="paper")
    parser.add_argument("--backtest", action="store_true")
    parser.add_argument("--start", help="backtest start, YYYY-MM-DD")
    parser.add_argument("--end", help="backtest end, YYYY-MM-DD")
    args = parser.parse_args()

    config = load_config()

    if args.backtest:
        return run_backtest(config, args)

    if args.mode == "live":
        print("\\n  LIVE MODE — real orders will be placed.")
        print(f"  Capital Rs {{config['capital']:,.0f}}, risk {{config['risk_pct']}}% per trade")
        if input("  Type LIVE to confirm: ").strip() != "LIVE":
            print("  Cancelled.")
            return 1

    runner = TradingRunner(config, mode=args.mode, state_dir=str(BOT_DIR / "state"),
                           log_dir=str(BOT_DIR / "logs"))
    try:
        runner.run()
    except PreflightError as exc:
        print(f"\\n  Preflight failed: {{exc}}")
        return 1
    return 0


def run_backtest(config: dict, args) -> int:
    from engine import backtest
    from engine.analytics import format_report
    from engine.broker import KiteBroker
    from engine.data import DataManager
    from engine.universe import load_universe

    if not args.start:
        print("  --start is required for a backtest")
        return 1

    start = datetime.fromisoformat(args.start)
    end = datetime.fromisoformat(args.end) if args.end else datetime.now()

    broker = KiteBroker(cache_dir=str(BOT_DIR / ".cache"))
    data = DataManager(broker, interval=config.get("interval", "minute"),
                       cache_dir=str(BOT_DIR / ".cache" / "ohlcv"))

    symbols = load_universe(BOT_DIR / config["universe_file"], max_age_days=None)
    print(f"  loading {{len(symbols)}} symbols...")

    frames, ticks = {{}}, {{}}
    for symbol in symbols:
        try:
            frame = data.with_indicators(symbol, start, end, config)
        except Exception as exc:
            print(f"    {{symbol}}: skipped ({{exc}})")
            continue
        if frame.height:
            frames[symbol] = frame
            ticks[symbol] = broker.tick_size(symbol)

    result = backtest.run(frames, config, strategy=config["strategy"],
                          starting_capital=config["capital"], tick_sizes=ticks)
    print(format_report(result.metrics))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
